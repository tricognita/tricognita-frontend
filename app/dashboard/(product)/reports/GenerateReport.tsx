"use client";

import { useState } from "react";
import { Button, HStack, VStack } from "@/lib/ui";
import { canDo } from "@/lib/rbac";
import { useSession } from "@/lib/use-session";
import { generateReport, monthOptions, trailingPeriod } from "@/lib/api/reports";
import type { Report } from "@/lib/domain";

/**
 * GenerateReport — produce a report for a period that is over.
 *
 * Shown only to roles that may run verifications (the operator tier the API requires). It never fakes
 * progress: the report appears when the API says it stored one, and a refusal (a period still in
 * progress, nothing verified in it, already generated) is shown in the API's own words.
 */
const FIELD =
  "rounded-[var(--radius)] border border-[var(--border)] bg-[var(--bg)] px-2 py-1.5 text-[var(--text-sm)] text-[var(--fg)]";

type Props =
  | { kind: "MONTHLY_ASSURANCE"; existing: Report[]; onGenerated: () => void }
  | { kind: "CUSTOMER_REVIEW"; existing: Report[]; onGenerated: () => void };

const WINDOWS = [
  { days: 30, label: "The last 30 days" },
  { days: 90, label: "The last 90 days" },
  { days: 365, label: "The last 12 months" },
];

export function GenerateReport(props: Props) {
  const { role } = useSession();
  const months = monthOptions(new Date());
  const [month, setMonth] = useState(0);
  const [windowDays, setWindowDays] = useState(30);
  const [state, setState] = useState<{ kind: "idle" } | { kind: "working" } | { kind: "error"; message: string } | { kind: "done" }>({ kind: "idle" });

  if (!canDo(role, "runVerification")) {
    return (
      <p className="text-[var(--text-xs)] text-[var(--fg-muted)] max-w-[70ch]">
        Reports are generated by an operator. Ask an administrator or SecOps engineer to produce one.
      </p>
    );
  }

  async function submit() {
    setState({ kind: "working" });
    try {
      if (props.kind === "MONTHLY_ASSURANCE") {
        const m = months[month];
        await generateReport({ kind: "MONTHLY_ASSURANCE", periodStart: m.start, periodEnd: m.end });
      } else {
        const p = trailingPeriod(windowDays, new Date());
        await generateReport({ kind: "CUSTOMER_REVIEW", periodStart: p.start, periodEnd: p.end });
      }
      setState({ kind: "done" });
      props.onGenerated();
    } catch (e) {
      setState({ kind: "error", message: e instanceof Error ? e.message : String(e) });
    }
  }

  return (
    <VStack gap="sm">
      <HStack gap="sm" align="end" className="flex-wrap">
        <label className="flex flex-col gap-1">
          <span className="text-[10px] uppercase tracking-wide text-[var(--fg-subtle)]">Period</span>
          {props.kind === "MONTHLY_ASSURANCE" ? (
            <select className={FIELD} value={month} onChange={(e) => setMonth(Number(e.target.value))} disabled={state.kind === "working"}>
              {months.map((m, i) => (
                <option key={m.start} value={i}>
                  {m.label}
                  {props.existing.some((r) => r.periodStart === m.start) ? " (already generated)" : ""}
                </option>
              ))}
            </select>
          ) : (
            <select className={FIELD} value={windowDays} onChange={(e) => setWindowDays(Number(e.target.value))} disabled={state.kind === "working"}>
              {WINDOWS.map((w) => (
                <option key={w.days} value={w.days}>
                  {w.label}
                </option>
              ))}
            </select>
          )}
        </label>
        <Button size="sm" onClick={() => void submit()} disabled={state.kind === "working"} loading={state.kind === "working"}>
          {props.kind === "MONTHLY_ASSURANCE" ? "Generate monthly report" : "Generate customer review"}
        </Button>
      </HStack>
      <div aria-live="polite" className="text-[var(--text-sm)]">
        {state.kind === "error" && (
          <p role="alert" className="text-[var(--fg)]">
            {state.message}
          </p>
        )}
        {state.kind === "done" && (
          <p role="status" className="text-[var(--fg)]">
            The report was generated and stored.
          </p>
        )}
      </div>
    </VStack>
  );
}
