test("18. every link resolves and every anchor has a target", () => {
  const hrefs = [...HTML.matchAll(/href="([^"]+)"/g)].map((m) => decode(m[1]));
  assert.ok(hrefs.length > 10);
  const retired = RETIRED_ROUTES.map((r) => r.source);
  for (const h of hrefs) {
    if (h.startsWith("#")) {
      assert.ok(HTML.includes(`id="${h.slice(1)}"`), `${h} has no target`);
      continue;
    }
    assert.ok(h.startsWith("/"), `external link ${h}`);
    const path = h.split(/[?#]/)[0].replace(/\/$/, "") || "/";
    assert.ok(!retired.includes(path), `links retired ${h}`);
    assert.ok(existsSync(join(MARKETING, path, "page.tsx")), `${h} → missing page`);
  }
  // Tap targets: every link is a button or at least 44px tall.
  for (const [a] of HTML.matchAll(/<a\b[^>]*>/g)) {
    assert.ok(/btn-2026|min-h-11/.test(a), `link below the tap-target size: ${a.slice(0, 90)}`);
  }
});

