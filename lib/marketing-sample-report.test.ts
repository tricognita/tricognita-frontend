test("15. the lifecycle runs assessment → remediation → verification → evidence → closure", () => {
  assert.deepEqual(CLOSURE.map((c) => c.stage), ["Finding", "Authorization", "Remediation", "Verification", "Evidence", "Closure"]);
  const v = textOf(section("verification"));
  assert.ok(v.indexOf("Before:") < v.indexOf("Change:") && v.indexOf("Change:") < v.indexOf("After:"));
  assert.match(v, /Before: Control checked.*Failing.*Change: Approved remediation applied.*Applied.*After: Same check run again.*Passing/);
  assert.deepEqual(OUTCOMES.map((o) => o.label), [REMEDIATION_VERDICT.REMEDIATED.label, REMEDIATION_VERDICT.NOT_EFFECTIVE.label, REMEDIATION_VERDICT.UNVERIFIED.label]);
  assert.deepEqual(OUTCOMES.map((o) => o.label), ["Fixed", "Did not fix it", "Unconfirmed"]);
  assert.deepEqual(OUTCOMES.filter((o) => o.thisSample).map((o) => o.label), ["Fixed"]);
  assert.ok(v.includes("The finding is not closed until the check runs again."));
  assert.ok(textOf(section("closure")).includes("Closed"));
  assert.deepEqual(ARIA_STEPS.map((s) => s.step), ["Evaluate", "Fix", "Verify", "Keep secure", "Evidence"]);
});

